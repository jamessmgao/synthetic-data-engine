"""Dry render of every instruction an authoring agent reads in P1, with token counts.

    python scripts/render_p1_prompts.py [out_dir]      (default output/p1/rendered)

Writes, without any model call or Docker run:
    world-<family>.md        the initial world instruction, one per taxonomy-v2 family
    world-repair.md          a world repair (after a failed world_check)
    world-mutation.md        a world mutation (too easy; operators from the Trace Parser)
    task-author.md           the task author's instruction, from the same parent world
    README.md                an index with the size of each (words, characters, tokens)

Tokens are counted with tiktoken's cl100k_base, an approximation of GLM-5.1's
tokenizer. The instruction is the agent's first message and stays in its context
for every step, so its size is paid again on every glm-5.1 call of the trial.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "generator"), str(ROOT / "validator"), str(ROOT)]

from generator import author  # noqa: E402
from generator import author_task  # noqa: E402
from shared.taxonomy.taxonomy import FAMILIES, shape_for  # noqa: E402

PARENT_WORLD = {
    "name": "inventory-reservations",
    "spec": {"family": "database_consistency", "mechanism": "isolation_anomaly", "shape": "fix",
             "environment": "Python service (SQLite)", "verification": "fault_injection", "dial": 2},
    "invariants": [
        "For each SKU, confirmed reservations never exceed the stock",
        "A retried reservation request (same request id) never reserves twice",
        "A confirmed reservation survives a service restart",
    ],
    "counterexample": {
        "sequence": ["client A: reserve sku-1 (stock 1), reads available=1",
                     "client B: reserve sku-1, reads available=1",
                     "A inserts its reservation and commits", "B inserts its reservation and commits"],
        "reproduce": "repro/repro.sh",
        "observed": "2 confirmed reservations for sku-1, stock 1"},
    "plausible_wrong_fix": "wrap the availability check and the insert in one transaction at the default isolation",
    "lineage": {"parent_world_sha256": None, "mutations": []},
}
PARENT_SHA = "0" * 64
MUTATION = {"operators": ["add_persistent_state", "extend_cross_component_dependency"],
            "why": "every passing run fixed it with an in-process lock in reserve()"}
MUTATION_INPUT = {
    "origin": "mutation", "parent_world_sha256": PARENT_SHA, "spec": PARENT_WORLD["spec"],
    "mutation": MUTATION, "mutations": [MUTATION],
    "analysis": {"why_easy": "the race is visible in one function, and a lock fixes it",
                 "simple_strategy": "add a threading.Lock around reserve()",
                 "fix_applied": "a process-local lock in reserve()",
                 "cues": [{"quote": "reservations are checked and written in reserve()", "where": "instruction"}]},
    "target_fix": "a threading.Lock around reserve() (a single-process fix)",
}


def tokens(text: str) -> int | None:
    try:
        import tiktoken
    except ImportError:
        return None
    return len(tiktoken.get_encoding("cl100k_base").encode(text))


def main(out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    rendered: dict[str, str] = {}
    for family, f in FAMILIES.items():
        spec = {"family": family, "mechanism": f.mechanisms[0], "shape": shape_for(f.mechanisms[0]),
                "environment": f.environments[0], "verification": f.verification[0], "dial": 2}
        rendered[f"world-{family}.md"] = author.render_world_instruction(spec)
    rendered["world-repair.md"] = author.render_world_instruction(
        PARENT_WORLD["spec"], "repair",
        "On the unfixed world, repro/repro.sh must exit 1 (an invariant is violated) every run; it exited [0, 1].")
    rendered["world-mutation.md"] = author_task.render_world_mutation_instruction(
        MUTATION_INPUT, PARENT_WORLD, "/input/parent", "/logs/artifacts/world")
    rendered["task-author.md"] = author_task.render_task_author_instruction(
        PARENT_WORLD, {"origin": "initial", "world_sha256": PARENT_SHA, "shape": "fix", "dial": 2}, "fix", 2)

    rows = []
    for name, text in rendered.items():
        (out_dir / name).write_text(text)
        rows.append((name, len(text.split()), len(text), tokens(text)))
    lines = ["# P1 rendered instructions", "",
             "Generated by `python scripts/render_p1_prompts.py`: the exact first message each",
             "authoring agent receives, with no model call. Tokens: tiktoken cl100k_base,",
             "an approximation of GLM-5.1's tokenizer; the instruction stays in context, so it",
             "is re-sent on every step of the trial.", "",
             "| File | Words | Characters | ~Tokens |", "|---|---:|---:|---:|"]
    lines += [f"| [{n}]({n}) | {w} | {c} | {t if t is not None else 'n/a'} |" for n, w, c, t in rows]
    (out_dir / "README.md").write_text("\n".join(lines) + "\n")
    print(json.dumps([{"file": n, "words": w, "chars": c, "tokens": t} for n, w, c, t in rows], indent=1))


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "output" / "p1" / "rendered")
